def keep_points(mid):
    """도착 자리 + 이 맵의 입구 가운데 + 다른 맵에서 이 맵으로 올 때의 도착 자리"""
    pts=[]; d=json.load(open(G+f'data/maps/{mid}.json'))
    pts.append((d['spawn']['x'],d['spawn']['y']))
    for p in d.get('portals',[]): pts.append((int(p['x']+p['w']/2),int(p['y']+p['h']/2)))
    for f in glob.glob(G+'data/maps/*.json'):
        for p in json.load(open(f)).get('portals',[]):
            if p.get('to')==mid and 'arrive' in p: pts.append((p['arrive']['x'],p['arrive']['y']))
    return pts
